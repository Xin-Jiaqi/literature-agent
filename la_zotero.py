"""literature-agent v1 Zotero 决策队列（本地 jsonl，不写 Zotero）。

只加入 MUST 和用户可能想收藏的 WEEKLY。
字段：work_id / title / grade / main_collection / compatible_collections / tags / reason / status / added_at
status: pending_user | accepted | rejected | deferred
"""
import json
import os
import re
from datetime import datetime

BASE = os.path.dirname(os.path.abspath(__file__))
from literature_config import QUEUES_ROOT
QUEUE_PATH = os.environ.get("LITAGENT_ZOTERO_QUEUE", os.path.join(QUEUES_ROOT, "zotero_queue.jsonl"))


def load_queue(path=None):
    path = path or QUEUE_PATH
    out = []
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            for ln in f:
                ln = ln.strip()
                if ln:
                    out.append(json.loads(ln))
    return out


def _save(entries, path=None):
    path = path or QUEUE_PATH
    with open(path, "w", encoding="utf-8") as f:
        for e in entries:
            f.write(json.dumps(e, ensure_ascii=False) + "\n")


def export_bibtex(conn, path=None, only_accepted=True):
    """把本地队列导出为 BibTeX（data/queues/zotero_export.bib），供 Zotero 一键拖入。

    只导出用户明确勾选“存 Zotero”的条目（status=accepted）；doi 是核心字段，
    Zotero 导入时会自动抓取作者/摘要等完整元数据，无需手动回浏览器建档。
    """
    path = path or os.environ.get("LITAGENT_ZOTERO_EXPORT") or os.path.join(QUEUES_ROOT, "zotero_export.bib")
    entries = load_queue()
    if only_accepted:
        entries = [e for e in entries if e.get("status") == "accepted"]
    seen, items = set(), []
    for e in entries:
        wid = e.get("work_id")
        if not wid or wid in seen:
            continue
        seen.add(wid)
        work = None
        if conn is not None:
            try:
                work = conn.execute("SELECT * FROM works WHERE work_id=?", (wid,)).fetchone()
            except Exception:
                work = None
        title = (work["title"] if work is not None else e.get("title")) or ""
        journal = (work["journal"] if work is not None else e.get("journal")) or ""
        doi = (work["doi"] if work is not None else wid if str(wid).startswith("10.") else "") or ""
        year = ""
        if work is not None:
            year = str(work["first_seen"] or "")[:4]
        if not year:
            year = str(e.get("added_at") or "")[:4]
        authors = ""
        if work is not None and work["authors"]:
            authors = work["authors"]
        key = re.sub(r"[^A-Za-z0-9_:.-]", "_", wid)
        fields = [f"  title = {{{title}}}"]
        if authors:
            fields.append(f"  author = {{{authors}}}")
        if journal:
            fields.append(f"  journal = {{{journal}}}")
        if year:
            fields.append(f"  year = {{{year}}}")
        if doi:
            fields.append(f"  doi = {{{doi}}}")
            fields.append(f"  url = {{https://doi.org/{doi}}}")
        elif work is not None and work["arxiv_id"]:
            fields.append(f"  url = {{https://arxiv.org/abs/{work['arxiv_id']}}}")
        items.append("@article{" + key + ",\n" + ",\n".join(fields) + "\n}\n")
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("% Generated by literature-agent " + datetime.now().strftime("%Y-%m-%d %H:%M") + "\n")
        f.write("% 拖入 Zotero 即可自动建档（DOI 自动抓取元数据）\n")
        f.write("\n".join(items))
    os.replace(tmp, path)
    return {"path": path, "count": len(items)}




# ---------------- Zotero Web API 自动建档（可选） ----------------

def _zotero_cfg():
    """读取 config/local.json 的 zotero 段：api_key / user_id / auto_sync。"""
    from literature_config import _load_local
    return (_load_local().get("zotero") or {})


def zotero_auto_enabled():
    z = _zotero_cfg()
    return bool(z.get("auto_sync") and z.get("api_key") and z.get("user_id"))


def _zotero_http(method, url, body=None, api_key=None, timeout=60,
                  content_type="application/json", headers=None):
    import urllib.request
    if body is None:
        data = None
    elif isinstance(body, bytes):
        data = body
    else:
        data = json.dumps(body).encode("utf-8")
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("Zotero-API-Key", api_key)
    req.add_header("Zotero-API-Version", "3")
    if data is not None:
        req.add_header("Content-Type", content_type)
    for k, v in (headers or {}).items():
        req.add_header(k, v)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return resp.status, resp.read()


def _zotero_collection_key(api_key, user_id, name):
    """按 collection 名精确匹配（用户库内分页查找）；找不到返回 None。"""
    start = 0
    while True:
        status, raw = _zotero_http(
            "GET", f"https://api.zotero.org/users/{user_id}/collections?limit=100&start={start}",
            api_key=api_key)
        if status != 200:
            return None
        cols = json.loads(raw)
        if not cols:
            return None
        for c in cols:
            if c.get("data", {}).get("name") == name:
                return c.get("key")
        if len(cols) < 100:
            return None
        start += 100


def _zotero_ensure_collection(api_key, user_id, name):
    """匹配用户已有 collection：完整路径 → 逐级后缀 → 才新建叶子名。

    用户库中 collection 是扁平名，例如 "04_injection/Ballistic"；
    suggestion 返回的是层级路径 "01_核心/02_BPVE/04_injection/Ballistic"，
    必须先尝试后缀匹配，避免每次都新建一个孤立的 "Ballistic"。
    """
    parts = (name or "").split("/")
    candidates = []
    for i in range(len(parts)):
        cand = "/".join(parts[i:])
        if cand and cand not in candidates:
            candidates.append(cand)
    for cand in candidates:
        key = _zotero_collection_key(api_key, user_id, cand)
        if key:
            return key
    leaf = parts[-1] or name
    status, raw = _zotero_http(
        "POST", f"https://api.zotero.org/users/{user_id}/collections",
        body=[{"name": leaf}], api_key=api_key)
    if status not in (200, 201):
        return None
    created = json.loads(raw)
    if isinstance(created, dict):
        succ = created.get("successful") or {}
        return (succ.get("0") or {}).get("key") if isinstance(succ, dict) else None
    if isinstance(created, list) and created:
        succ = created[0].get("successful") or {}
        return (succ.get("0") or {}).get("key") if isinstance(succ, dict) else None
    return None


def _webdav_cfg():
    """可选 WebDAV 文件同步配置（config/local.json 的 zotero.webdav）。

    用户 Zotero 若配置了 WebDAV（如坚果云），API 上传到 zotero.org 官方存储的
    文件永远不会被本地客户端下载；配置本段后附件改为 PUT 到 WebDAV，
    并 PATCH API 的 md5/mtime 让客户端认为文件已存在。留空则走官方上传。
    """
    return (_zotero_cfg().get("webdav") or {})


def _webdav_upload(api_key, user_id, att_key, pdf_path):
    """按 Zotero 7+ WebDAV 格式上传附件：<key>.zip + <key>.prop + API md5/mtime。

    用户坚果云上现有格式为 /dav/zotero/<itemKey>.zip（单文件 zip 包）与
    <itemKey>.prop（<properties version="1"><mtime>..</mtime><hash>..</hash>）。
    hash=文件 MD5、mtime=毫秒时间戳，均与 Zotero API 的 md5/mtime 一致，
    本地客户端据此判断 WebDAV 上的文件是否为最新。返回 (ok, detail)。
    """
    import base64
    import hashlib
    import io
    import zipfile
    import urllib.request
    cfg = _webdav_cfg()
    base = (cfg.get("url") or "").rstrip("/")
    username = cfg.get("username") or ""
    password = cfg.get("password") or ""
    if not (base and username and password):
        return None, "webdav 未配置"
    with open(pdf_path, "rb") as f:
        data = f.read()
    md5 = hashlib.md5(data).hexdigest()
    mtime = int(os.path.getmtime(pdf_path) * 1000)
    fname = os.path.basename(pdf_path)

    # 单文件 zip 包（Zotero 7+ WebDAV 格式）
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(fname, data)
    zip_bytes = buf.getvalue()
    prop_xml = (f'<properties version="1"><mtime>{mtime}</mtime>'
                f'<hash>{md5}</hash></properties>').encode("utf-8")

    def _put(path, body, content_type):
        req = urllib.request.Request(path, data=body, method="PUT")
        req.add_header("Authorization", "Basic " + base64.b64encode(
            f"{username}:{password}".encode("utf-8")).decode("ascii"))
        req.add_header("Content-Type", content_type)
        try:
            with urllib.request.urlopen(req, timeout=300) as resp:
                return resp.status in (200, 201, 204), resp.status
        except Exception as e:
            return False, str(e)

    ok, st = _put(f"{base}/zotero/{att_key}.zip", zip_bytes, "application/zip")
    if not ok:
        return False, f"webdav PUT zip http {st}"
    ok, st = _put(f"{base}/zotero/{att_key}.prop", prop_xml, "application/xml")
    if not ok:
        return False, f"webdav PUT prop http {st}"
    try:
        st, raw = _zotero_http("GET", f"https://api.zotero.org/users/{user_id}/items/{att_key}",
                               api_key=api_key)
        if st != 200:
            return False, f"webdav register get http {st}"
        ver = json.loads(raw)["version"]
        st, raw = _zotero_http("PATCH", f"https://api.zotero.org/users/{user_id}/items/{att_key}",
                               body={"md5": md5, "mtime": mtime}, api_key=api_key,
                               headers={"If-Unmodified-Since-Version": str(ver)})
        if st != 204:
            return False, f"webdav register md5 http {st}"
    except Exception as e:
        return False, f"webdav register {e}"
    return True, ""


def _zotero_upload_pdf(api_key, user_id, parent_key, pdf_path):
    """上传 PDF 附件。返回 (ok, detail)。

    优先 WebDAV（用户配置了 webdav 段时）；否则走官方三步上传：
    建附件条目 → 授权 → 传文件 → 注册。
    v3 不再接受在条目创建时内嵌 base64 content。
    """
    import hashlib
    import urllib.parse
    with open(pdf_path, "rb") as f:
        pdf = f.read()
    md5 = hashlib.md5(pdf).hexdigest()
    fname = os.path.basename(pdf_path)
    mtime = str(int(os.path.getmtime(pdf_path) * 1000))
    # 1) 建附件条目（两种上传方式共用；不带 content）
    att = [{"itemType": "attachment", "linkMode": "imported_file",
            "filename": fname, "parentItem": parent_key, "title": fname}]
    status, raw = _zotero_http("POST", f"https://api.zotero.org/users/{user_id}/items",
                               body=att, api_key=api_key)
    if status not in (200, 201):
        return False, f"create attachment http {status}: {raw[:200]}"
    created = json.loads(raw)
    if isinstance(created, dict):
        succ = created.get("successful") or {}
    elif created:
        succ = created[0].get("successful") or {}
    else:
        succ = {}
    if isinstance(succ, dict):
        att_key = (succ.get("0") or {}).get("key")
    elif isinstance(succ, list) and succ:
        att_key = (succ[0] or {}).get("key")
    else:
        att_key = None
    if not att_key:
        return False, f"no attachment key: {raw[:200]}"

    def _cleanup():
        try:
            _zotero_http("DELETE", f"https://api.zotero.org/users/{user_id}/items?itemKey={att_key}",
                         api_key=api_key)
        except Exception:
            pass

    # 1b) WebDAV 模式：PUT 文件 + PATCH md5/mtime（不占官方存储配额）
    if _webdav_cfg().get("url"):
        ok_w, detail_w = _webdav_upload(api_key, user_id, att_key, pdf_path)
        if not ok_w:
            _cleanup()
            return False, f"webdav upload failed: {detail_w}"
        return True, ""

    # 2) 授权上传
    auth_body = urllib.parse.urlencode(
        {"md5": md5, "filename": fname, "filesize": len(pdf), "mtime": mtime}).encode()
    try:
        status, raw = _zotero_http(
            "POST", f"https://api.zotero.org/users/{user_id}/items/{att_key}/file",
            body=auth_body, api_key=api_key,
            content_type="application/x-www-form-urlencoded", headers={"If-None-Match": "*"})
    except Exception:
        _cleanup()
        raise
    if status != 200:
        _cleanup()
        return False, f"upload auth http {status}: {raw[:200]}"
    auth = json.loads(raw)
    if auth.get("exists"):
        return True, ""
    # 3) 传文件到临时 URL
    payload = auth["prefix"].encode("utf-8") + pdf + auth["suffix"].encode("utf-8")
    try:
        status, raw = _zotero_http("POST", auth["url"], body=payload, api_key=api_key,
                                   content_type=auth.get("contentType", "application/octet-stream"),
                                   timeout=300)
    except Exception:
        _cleanup()
        raise
    if status != 201:
        _cleanup()
        return False, f"upload file http {status}: {raw[:200]}"
    # 4) 注册
    reg_body = urllib.parse.urlencode({"upload": auth["uploadKey"]}).encode()
    try:
        status, raw = _zotero_http(
            "POST", f"https://api.zotero.org/users/{user_id}/items/{att_key}/file",
            body=reg_body, api_key=api_key,
            content_type="application/x-www-form-urlencoded", headers={"If-None-Match": "*"})
    except Exception:
        _cleanup()
        raise
    if status != 204:
        _cleanup()
        return False, f"register upload http {status}: {raw[:200]}"
    return True, ""


def _creators_from_authors(authors):
    """把 works.authors 转 Zotero creators。

    支持两种常见格式："Given Family; Given Family" 与 "Family, Given; Family, Given"。
    """
    out = []
    for name in re.split(r";", authors or ""):
        name = name.strip()
        if not name:
            continue
        if "," in name:
            fam, given = [p.strip() for p in name.split(",", 1)]
            out.append({"creatorType": "author", "firstName": given, "lastName": fam})
            continue
        parts = name.split()
        if len(parts) >= 2:
            out.append({"creatorType": "author", "firstName": " ".join(parts[:-1]), "lastName": parts[-1]})
        else:
            out.append({"creatorType": "author", "firstName": "", "lastName": name})
    return out


def zotero_save_work(conn, work_id):
    """把一篇论文自动建档到 Zotero（Web API）：条目 + PDF 附件 + collection + tags。

    要求 config/local.json 已配置 zotero.api_key / zotero.user_id / zotero.auto_sync=true。
    失败时返回 error，条目保留在本地队列，zotero_export.bib 仍可兜底。
    """
    from literature_config import PAPERS_ROOT
    from la_workflow import valid_pdf_file, workflow_item
    z = _zotero_cfg()
    if not zotero_auto_enabled():
        return {"ok": False, "error": "zotero auto_sync 未启用（config/local.json 缺少 api_key/user_id/auto_sync）"}
    api_key, user_id = z["api_key"], z["user_id"]
    work = conn.execute("SELECT * FROM works WHERE work_id=?", (work_id,)).fetchone()
    if work is None:
        return {"ok": False, "error": "work not found"}
    item = workflow_item(conn, work_id)
    pdf_path = (item or {}).get("pdf_path", "")
    if pdf_path and not os.path.isabs(pdf_path):
        pdf_path = os.path.join(PAPERS_ROOT, pdf_path) if False else pdf_path
    entry = {
        "itemType": "journalArticle",
        "title": work["title"] or "",
        "creators": _creators_from_authors(work["authors"]),
        "date": (work["first_seen"] or "")[:4],
        "url": "",
        "tags": [],
    }
    if work["doi"]:
        entry["DOI"] = work["doi"]
        entry["url"] = f"https://doi.org/{work['doi']}"
    elif work["arxiv_id"]:
        entry["url"] = f"https://arxiv.org/abs/{work['arxiv_id']}"
    if work["journal"] and work["journal"] not in ("arXiv", "arxiv"):
        entry["publicationTitle"] = work["journal"]
    main_coll = ""
    try:
        from literature_agent import zotero_suggestion
        screen = conn.execute("SELECT * FROM screenings WHERE work_id=? ORDER BY id DESC LIMIT 1",
                              (work_id,)).fetchone()
        if screen:
            main, _compat, ztags = zotero_suggestion(work, screen)
            main_coll = main or ""
            entry["tags"] = [{"tag": t} for t in (ztags or []) if t]
    except Exception:
        pass
    try:
        status, raw = _zotero_http("POST", f"https://api.zotero.org/users/{user_id}/items",
                                   body=[entry], api_key=api_key)
        if status not in (200, 201):
            return {"ok": False, "error": f"create item http {status}: {raw[:200]}"}
        created = json.loads(raw)
        item_key = None
        if isinstance(created, dict):
            succ = created.get("successful") or {}
        elif created:
            succ = created[0].get("successful") or {}
        else:
            succ = {}
        if isinstance(succ, dict):
            item_key = (succ.get("0") or {}).get("key")
        elif isinstance(succ, list) and succ:
            item_key = (succ[0] or {}).get("key")
        if not item_key:
            return {"ok": False, "error": f"no item key in response: {raw[:200]}"}
        item_version = None
        if isinstance(succ, dict):
            item_version = (succ.get("0") or {}).get("version")
        elif isinstance(succ, list) and succ:
            item_version = (succ[0] or {}).get("version")
        if main_coll:
            coll_key = _zotero_ensure_collection(api_key, user_id, main_coll)
            if coll_key:
                headers = {}
                if item_version is not None:
                    headers["If-Unmodified-Since-Version"] = str(item_version)
                _zotero_http("PATCH", f"https://api.zotero.org/users/{user_id}/items/{item_key}",
                             body={"collections": [coll_key]}, api_key=api_key, headers=headers)
        # 附件：官方三步上传（建条目 → 授权 → 传文件 → 注册）
        if pdf_path and os.path.exists(pdf_path) and valid_pdf_file(pdf_path):
            ok_up, detail = _zotero_upload_pdf(api_key, user_id, item_key, pdf_path)
            if not ok_up:
                try:
                    _zotero_http("DELETE", f"https://api.zotero.org/users/{user_id}/items?itemKey={item_key}",
                                 api_key=api_key)
                except Exception:
                    pass
                return {"ok": False, "error": f"attachment failed: {detail}"}
        return {"ok": True, "item_key": item_key, "collection": main_coll}
    except Exception as e:
        return {"ok": False, "error": str(e)}


def zotero_sync_queue(conn):
    """把本地队列中 accepted 且未同步的条目推送到 Zotero（幂等）。"""
    from la_v2common import now_iso
    if not zotero_auto_enabled():
        return {"ok": False, "error": "zotero auto_sync 未启用", "synced": 0, "failed": 0}
    entries = load_queue()
    synced, failed, errors = 0, 0, []
    changed = False
    now = now_iso()
    for e in entries:
        if e.get("status") != "accepted" or e.get("zotero_synced_at"):
            continue
        last = e.get("zotero_last_attempt")
        if last:
            try:
                dt = datetime.strptime(last, "%Y-%m-%d %H:%M:%S")
                backoff = float(e.get("zotero_backoff_hours") or 6)
                if (datetime.now() - dt).total_seconds() < backoff * 3600:
                    continue
            except ValueError:
                pass
        r = zotero_save_work(conn, e["work_id"])
        if r.get("ok"):
            e["zotero_synced_at"] = now
            e["zotero_item_key"] = r.get("item_key", "")
            e.pop("zotero_error", None)
            e.pop("zotero_last_attempt", None)
            e.pop("zotero_backoff_hours", None)
            synced += 1
            changed = True
        else:
            err = r.get("error", "")
            e["zotero_error"] = err
            e["zotero_last_attempt"] = now
            e["zotero_backoff_hours"] = 24 if "quota" in err else 6
            failed += 1
            changed = True
            errors.append({"work_id": e["work_id"], "error": err})
    if changed:
        _save(entries)
    return {"ok": True, "synced": synced, "failed": failed, "errors": errors[:5]}

def generate_queue(conn, today=None, log=None):
    """把当天新筛选的 S 与 A 加入队列（已存在的同 work_id 不重复加）。"""
    if log is None:
        log = lambda *a: None
    import literature_agent as la
    today = today or datetime.now().strftime("%Y-%m-%d")
    existing = {e["work_id"] for e in load_queue()}
    rows = conn.execute("""SELECT s.*, w.title FROM screenings s JOIN works w ON w.work_id=s.work_id
        WHERE w.consumed_history=0 AND date(s.screened_at)=? AND s.grade IN ('MUST','WEEKLY')
        ORDER BY s.id""", (today,)).fetchall()
    added = 0
    entries = load_queue()
    for s in rows:
        if s["work_id"] in existing:
            continue
        work = conn.execute("SELECT * FROM works WHERE work_id=?", (s["work_id"],)).fetchone()
        main, compat, ztags = la.zotero_suggestion(work, s)
        entries.append({"work_id": s["work_id"], "title": s["title"], "grade": s["grade"],
                        "main_collection": main, "compatible_collections": compat,
                        "tags": ztags, "reason": s["reason"], "status": "pending_user",
                        "added_at": datetime.now().strftime("%Y-%m-%d %H:%M")})
        existing.add(s["work_id"])
        added += 1
    if added:
        _save(entries)
        log("zotero", f"{added} items queued")
    return added


def mark(work_id, status, log=None):
    if log is None:
        log = lambda *a: None
    if status not in ("accept", "reject", "defer"):
        raise ValueError("status must be accept|reject|defer")
    entries = load_queue()
    hit = [e for e in entries if e["work_id"] == work_id]
    if not hit:
        return False
    new_status = {"accept": "accepted", "reject": "rejected", "defer": "deferred"}[status]
    for e in entries:
        if e["work_id"] == work_id and e["status"] == "pending_user":
            e["status"] = new_status
            e["reviewed_at"] = datetime.now().strftime("%Y-%m-%d %H:%M")
            log("zotero", f"{work_id} -> {new_status}")
    _save(entries)
    return True


def queue_status(conn):
    entries = load_queue()
    stats = {}
    for e in entries:
        stats[e["status"]] = stats.get(e["status"], 0) + 1
    return entries, stats
